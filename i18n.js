function cesykGetUrlLanguage() {
  const urlLanguage = new URLSearchParams(window.location.search).get("lang");
  return CESYK_TRANSLATIONS[urlLanguage] ? urlLanguage : "";
}

function cesykGetLanguage() {
  if (CESYK_TRANSLATIONS[cesykAppliedLanguageOverride]) {
    return cesykAppliedLanguageOverride;
  }

  const urlLanguage = cesykGetUrlLanguage();
  if (urlLanguage) {
    return urlLanguage;
  }

  const savedLanguage = localStorage.getItem(CESYK_LANGUAGE_KEY);
  return CESYK_TRANSLATIONS[savedLanguage] ? savedLanguage : "en";
}

function cesykTranslate(key, fallback = "") {
  const language = cesykGetLanguage();
  return CESYK_TRANSLATIONS[language][key] || CESYK_TRANSLATIONS.en[key] || fallback || key;
}

function setText(selector, key) {
  document.querySelectorAll(selector).forEach((element) => {
    element.textContent = cesykTranslate(key);
  });
}

function setPlaceholder(selector, key) {
  document.querySelectorAll(selector).forEach((element) => {
    element.placeholder = cesykTranslate(key);
  });
}

