function updateLanguageLinks(language) {
  document.querySelectorAll("a.page-link").forEach((link) => {
    const url = new URL(link.getAttribute("href"), window.location.href);
    url.searchParams.set("lang", language);
    link.href = url.pathname.split("/").pop() + url.search;
  });
}

function setupCesykLanguageControls() {
  document.querySelectorAll(".language-select").forEach((select) => {
    select.value = cesykGetLanguage();
  });

  document.querySelectorAll(".language-apply").forEach((button) => {
    button.addEventListener("click", (event) => {
      event.preventDefault();
      event.stopPropagation();

      const select = document.querySelector(".language-select");
      if (!select) {
        return;
      }

      cesykAppliedLanguageOverride = select.value;
      localStorage.setItem(CESYK_LANGUAGE_KEY, cesykAppliedLanguageOverride);
      const url = new URL(window.location.href);
      url.searchParams.set("lang", cesykAppliedLanguageOverride);
      window.history.replaceState(null, "", url.toString());
      applyCesykLanguage();
      window.dispatchEvent(new CustomEvent("cesyk-language-change"));
    });
  });

  applyCesykLanguage();
}

window.cesykTranslate = cesykTranslate;
